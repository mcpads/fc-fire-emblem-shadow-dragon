#[derive(Clone, Copy)]
pub(super) enum RegionKind {
    Code,
    Data,
}

#[derive(Clone, Copy)]
pub(super) enum RegionExpectation {
    Bytes(&'static [u8]),
    Sha1 {
        byte_count: usize,
        expected_sha1: &'static str,
    },
}

#[derive(Clone, Copy)]
pub(super) struct SourceRegionSpec {
    pub(super) role: &'static str,
    pub(super) prg_bank: u8,
    pub(super) cpu_address: u16,
    pub(super) expectation: RegionExpectation,
    pub(super) kind: RegionKind,
}

impl SourceRegionSpec {
    const fn code(
        role: &'static str,
        prg_bank: u8,
        cpu_address: u16,
        bytes: &'static [u8],
    ) -> Self {
        Self {
            role,
            prg_bank,
            cpu_address,
            expectation: RegionExpectation::Bytes(bytes),
            kind: RegionKind::Code,
        }
    }

    const fn code_sha1(
        role: &'static str,
        prg_bank: u8,
        cpu_address: u16,
        byte_count: usize,
        expected_sha1: &'static str,
    ) -> Self {
        Self {
            role,
            prg_bank,
            cpu_address,
            expectation: RegionExpectation::Sha1 {
                byte_count,
                expected_sha1,
            },
            kind: RegionKind::Code,
        }
    }

    const fn data(
        role: &'static str,
        prg_bank: u8,
        cpu_address: u16,
        bytes: &'static [u8],
    ) -> Self {
        Self {
            role,
            prg_bank,
            cpu_address,
            expectation: RegionExpectation::Bytes(bytes),
            kind: RegionKind::Data,
        }
    }

    const fn data_sha1(
        role: &'static str,
        prg_bank: u8,
        cpu_address: u16,
        byte_count: usize,
        expected_sha1: &'static str,
    ) -> Self {
        Self {
            role,
            prg_bank,
            cpu_address,
            expectation: RegionExpectation::Sha1 {
                byte_count,
                expected_sha1,
            },
            kind: RegionKind::Data,
        }
    }
}
